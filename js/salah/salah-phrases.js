var _salahPhraseIndex = null;

/** The phrase record with this id, or null. */
function getSalahPhrase(id) {
  if (!_salahPhraseIndex) {
    _salahPhraseIndex = {};
    SALAH_PHRASES.forEach(function(p) { _salahPhraseIndex[p.id] = p; });
  }
  return _salahPhraseIndex[id] || null;
}

/** A test: does a learner of this madhab say the phrase with this id? */
function salahPhraseFor(madhab) {
  return function(id) {
    var p = getSalahPhrase(id);
    return !!p && (!p.madhab || p.madhab.indexOf(madhab) >= 0);
  };
}
