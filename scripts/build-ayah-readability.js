/**
 * build-ayah-readability.js — which words of each ayah a learner can know
 *
 * Writes js/quran/ayah-readability.js, the index behind Today's ayah
 * (docs/superpowers/specs/2026-11-16-daily-ayah-design.md). For every ayah
 * of 4 or more words, one entry per word:
 *   N     the word is lesson word cw_N
 *   "+N"  وَ or فَ ("and", "so") plus lesson word cw_N
 *   null  not a lesson word: the learner gets a hint
 * A word is tagged only when the matcher that credits % of the Quran
 * (scripts/build-occurrence-index.js) credits it to exactly one lesson
 * word; anything less certain is a hint. Ayahs the picker could never
 * choose are left out: under half the words knowable, or over 3 hints.
 *
 * Run: node scripts/build-ayah-readability.js
 */
'use strict';

var fs = require('fs');
var path = require('path');
var arabicSameWord = require('../js/data-core/word-forms.js').arabicSameWord;
var occ = require('./build-occurrence-index.js');
var wordMeanings = require('./word-meanings.js');
var dailyAyahWords = require('../js/data-core/daily-ayah.js').dailyAyahWords;

var ROOT = path.join(__dirname, '..');
var OUT_PATH = path.join(ROOT, 'js', 'quran', 'ayah-readability.js');
var MIN_WORDS = 4;
var MAX_HINTS = 3;                 // the picker never shows more (js/data-core/daily-ayah.js)
var AND_SO = /^[وف]َ/;            // وَ or فَ at the start of a word
var AND_SO_MEANING = /^(and|so|then)\b/i;

function loadInputs() {
  var quranText = occ.loadQuranCorpus();
  var words = require('../test/load-vocabulary.js').loadVocabularyWords();
  var meanings = wordMeanings.alignWordMeanings(quranText, wordMeanings.loadSource(), occ.normalizeArabic);
  if (meanings.errors.length) throw new Error('word meanings: ' + meanings.errors[0]);
  return { quranText: quranText, words: words, meanings: meanings.bySurah };
}

function buildAyahReadability(quranText, words, meaningsBySurah) {
  var forms = occ.buildFormKeys(quranText, words);
  var idsByKey = {};
  words.forEach(function (w) {
    var form = String(w.arabic || '').trim();
    if (!form || /\s/.test(form)) return;
    var key = forms.formKeys[form] || occ.normalizeArabic(form);
    (idsByKey[key] = idsByKey[key] || []).push(w);
  });

  // The one lesson word this token is, or null when none or several
  function wordId(token) {
    var key = forms.tokenKey(token);
    if (!key) return null;
    var ids = {};
    (idsByKey[key] || []).forEach(function (w) {
      if (arabicSameWord(w.arabic, token)) ids[Number(w.id.slice(3))] = true;
    });
    var list = Object.keys(ids);
    return list.length === 1 ? Number(list[0]) : null;
  }

  function entry(token, meaning) {
    if (/\s/.test(token)) return null;
    var id = wordId(token);
    if (id !== null) return id;
    if (!AND_SO.test(token) || !AND_SO_MEANING.test(meaning || '')) return null;
    id = wordId(token.slice(2));
    return id === null ? null : '+' + id;
  }

  var index = {};
  for (var s = 1; s <= 114; s++) {
    quranText[s].verses.forEach(function (verse, i) {
      var m = meaningsBySurah[s][i];
      var words = dailyAyahWords(verse.text, m);
      if (words.length < MIN_WORDS) return;
      var entries = words.map(function (w) { return entry(w.text, w.meaning); });
      var known = entries.filter(function (e) { return e !== null; }).length;
      var hints = entries.length - known;
      if (known * 2 >= entries.length && hints <= MAX_HINTS) index[s + ':' + verse.id] = entries;
    });
  }
  return index;
}

function generateFile(index) {
  var refs = Object.keys(index);
  return '// Generated by scripts/build-ayah-readability.js — do not edit by hand.\n' +
    '// Today\'s ayah: per ayah, each word as lesson word N (cw_N), "+N" (وَ/فَ + cw_N)\n' +
    '// or null (a hint). ' + refs.length + ' ayahs.\n' +
    'window.__AYAH_READABILITY = {\n' +
    refs.map(function (r) { return '"' + r + '":' + JSON.stringify(index[r]); }).join(',\n') +
    '\n};\n';
}

function main() {
  var inputs = loadInputs();
  var index = buildAyahReadability(inputs.quranText, inputs.words, inputs.meanings);
  var out = generateFile(index);
  fs.writeFileSync(OUT_PATH, out, 'utf8');
  console.log('Wrote js/quran/ayah-readability.js: ' + Object.keys(index).length + ' ayahs, ' +
    (Buffer.byteLength(out) / 1024).toFixed(1) + ' KB');
}

if (require.main === module) main();

module.exports = {
  loadInputs: loadInputs,
  buildAyahReadability: buildAyahReadability,
  generateFile: generateFile,
};
