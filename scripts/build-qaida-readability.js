#!/usr/bin/env node
/**
 * scripts/build-qaida-readability.js
 *
 * Builds js/qaida/qaida-readability.js from the Quran text
 * (js/quran/quran-data.js) and the skill rules in js/qaida/:
 *
 *   QAIDA_READABLE_PERCENT
 *     For "% of the Quran's words you can read", by lesson id: the share
 *     of the Quran's word occurrences (whitespace-separated tokens, the
 *     same 77,429 the coverage figure counts) whose every letter and mark
 *     is taught by that lesson or an earlier one. Lessons open strictly in
 *     order and placement skips whole levels, so what a learner knows is
 *     always "everything up to some lesson" and one figure per lesson is
 *     enough.
 *
 *   QAIDA_EXAMPLES
 *     Real Quran words for each lesson from Elementary on: the most
 *     frequent words readable at that lesson, preferring ones that use
 *     what the lesson teaches.
 *
 * Usage: node scripts/build-qaida-readability.js
 * Rerun after changing js/qaida/qaida-marks.js or qaida-lessons.js.
 */

var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var EXAMPLES_PER_LESSON = 12;

function load(rel) { (0, eval)(fs.readFileSync(path.join(ROOT, rel), 'utf8')); }
load('js/qaida/qaida-letters.js');
load('js/qaida/qaida-marks.js');
load('js/qaida/qaida-lessons.js');

global.window = {};
new Function(fs.readFileSync(path.join(ROOT, 'js/quran/quran-data.js'), 'utf8'))();
var QURAN = global.window.__QURAN_TEXT;

// Pause, sajdah and other signs written on a word: fine to read past,
// but example words are shown without them.
var SIGNS = /[ۖ-۞ۣۢۨ-ۭ]/;

var total = 0;
var counts = {};
for (var sid = 1; sid <= 114; sid++) {
  QURAN[sid].verses.forEach(function (v) {
    v.text.split(/\s+/).forEach(function (token) {
      token = token.trim();
      if (!token) return;
      total++;
      counts[token] = (counts[token] || 0) + 1;
    });
  });
}

var words = Object.keys(counts).map(function (w) {
  return { word: w, count: counts[w], skills: qaidaWordSkills(w) };
}).sort(function (a, b) { return b.count - a.count || (a.word < b.word ? -1 : 1); });

function readableWith(lessonId) {
  var known = {};
  getQaidaSkillsThrough(lessonId).forEach(function (s) { known[s] = true; });
  return words.filter(function (w) { return w.skills.every(function (s) { return known[s]; }); });
}

var percent = {};
var examples = {};
QAIDA_LESSONS.forEach(function (lesson) {
  var readable = readableWith(lesson.id);
  var n = readable.reduce(function (sum, w) { return sum + w.count; }, 0);
  percent[lesson.id] = Math.round(n / total * 10000) / 100;

  if (lesson.level === 0 || lesson.kind === 'surah') return;
  var clean = readable.filter(function (w) { return w.skills.length > 0 && !SIGNS.test(w.word); });
  var uses = clean.filter(function (w) {
    return lesson.teaches.some(function (s) { return w.skills.indexOf(s) >= 0; });
  });
  var picked = (uses.length ? uses : clean).slice(0, EXAMPLES_PER_LESSON);
  if (picked.length) examples[lesson.id] = picked.map(function (w) { return w.word; });
});

fs.writeFileSync(path.join(ROOT, 'js/qaida/qaida-readability.js'),
  '// Generated by scripts/build-qaida-readability.js — do not edit by hand.\n\n' +
  '// Total word occurrences in the Quran text\n' +
  'var QAIDA_WORD_TOTAL = ' + total + ';\n\n' +
  '// % of the Quran\'s words readable once a lesson and all before it are learned\n' +
  'var QAIDA_READABLE_PERCENT = ' + JSON.stringify(percent, null, 2) + ';\n\n' +
  '// Frequent Quran words readable at each lesson, by lesson id\n' +
  'var QAIDA_EXAMPLES = ' + JSON.stringify(examples, null, 2) + ';\n');

console.log('Words: ' + total + ', lessons with examples: ' + Object.keys(examples).length);
QAIDA_LESSONS.forEach(function (l) { console.log('  ' + l.id + '  ' + percent[l.id] + '%'); });
