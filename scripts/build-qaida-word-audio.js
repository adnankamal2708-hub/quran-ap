#!/usr/bin/env node
/**
 * scripts/build-qaida-word-audio.js
 *
 * Builds js/qaida/qaida-word-audio.js, which lets the Qaida play quran.com's
 * recording of the real Quran words it shows (the same voice as the
 * word-by-word audio in the Quran reader):
 *
 *   QAIDA_LETTER_WORDS
 *     For each of the 28 letters, a word that starts with it, so a beginner
 *     hears the letter's sound at the start of a real word: the most
 *     frequent short word (2–4 letters) beginning with that letter, without
 *     pause signs. Alif uses a word starting with أ (hamza on alif), the
 *     way it is first heard.
 *
 *   QAIDA_WORD_REFS
 *     Where each shown word is recorded: {word: [surah, verse, [numbers]]},
 *     its first place in the Quran, with quran.com's word numbers
 *     (quranWordPositions in js/services/audio.js). Covers the letter words,
 *     every word in QAIDA_EXAMPLES and the muqattaat lesson's openings.
 *
 * Usage: node scripts/build-qaida-word-audio.js
 * Rerun after build-qaida-readability.js or a change to the lessons.
 */

var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
function load(rel) { (0, eval)(fs.readFileSync(path.join(ROOT, rel), 'utf8')); }
global.escapeHtml = function (s) { return s; };
load('js/qaida/qaida-letters.js');
load('js/qaida/qaida-lessons.js');
load('js/qaida/qaida-readability.js');
load('js/services/audio.js');

global.window = {};
new Function(fs.readFileSync(path.join(ROOT, 'js/quran/quran-data.js'), 'utf8'))();
new Function(fs.readFileSync(path.join(ROOT, 'js/data/occurrence-index.js'), 'utf8')).call(global);
var QURAN = global.window.__QURAN_TEXT;
var wm = require('./word-meanings.js');
var aligned = wm.alignWordMeanings(QURAN, wm.loadSource(), global.window.OCCURRENCE_INDEX_NORM);
if (aligned.errors.length) throw new Error('Word meanings do not line up: ' + aligned.errors[0]);

var SIGNS = /[ۖ-۞ۣۢۨ-ۭ]/;
var ARABIC_LETTER = /[ء-ي]/g;
function lettersOf(word) { return (word.replace(/ٱ/g, 'ا').match(ARABIC_LETTER) || []).join(''); }

// Every word's first place, and how often it occurs
var firstRef = {};
var count = {};
var byLetters = {}; // bare letters → first word with them (for the openings)
for (var sid = 1; sid <= 114; sid++) {
  QURAN[sid].verses.forEach(function (v, vi) {
    var tokens = v.text.split(/\s+/).filter(Boolean);
    var positions = quranWordPositions(tokens.length, aligned.bySurah[sid][vi], aligned.splitsBySurah[sid][vi]);
    tokens.forEach(function (token, i) {
      count[token] = (count[token] || 0) + 1;
      // A word that continues the one before has no recording of its own
      if (firstRef[token] || !positions[i].length) return;
      firstRef[token] = [sid, v.id, positions[i]];
      var bare = lettersOf(token);
      if (!byLetters[bare]) byLetters[bare] = token;
    });
  });
}

var letterWords = {};
QAIDA_LETTERS.forEach(function (letter) {
  var first = letter.id === 'alif' ? 'أ' : letter.char;
  var best = null;
  Object.keys(firstRef).forEach(function (w) {
    if (w.charAt(0) !== first || SIGNS.test(w)) return;
    var n = lettersOf(w).length;
    if (n < 2 || n > 4) return;
    if (!best || count[w] > count[best] || (count[w] === count[best] && w < best)) best = w;
  });
  if (!best) throw new Error('No word starts with ' + letter.char);
  letterWords[letter.id] = best;
});

var refs = {};
function addRef(word) {
  if (!firstRef[word]) throw new Error('Not a Quran word: ' + word);
  refs[word] = firstRef[word];
}
Object.keys(letterWords).forEach(function (id) { addRef(letterWords[id]); });
Object.keys(QAIDA_EXAMPLES).forEach(function (id) { QAIDA_EXAMPLES[id].forEach(addRef); });
QAIDA_LESSONS.forEach(function (lesson) {
  (lesson.kind === 'muqattaat' ? lesson.examples : []).forEach(function (opening) {
    var word = byLetters[opening];
    if (!word) throw new Error('No Quran word spells ' + opening);
    refs[opening] = firstRef[word];
  });
});

fs.writeFileSync(path.join(ROOT, 'js/qaida/qaida-word-audio.js'),
  '// Generated by scripts/build-qaida-word-audio.js — do not edit by hand.\n\n' +
  '// A short, frequent Quran word starting with each letter\n' +
  'var QAIDA_LETTER_WORDS = ' + JSON.stringify(letterWords, null, 2) + ';\n\n' +
  '// Where each shown word is recorded: [surah, verse, quran.com word numbers]\n' +
  'var QAIDA_WORD_REFS = ' + JSON.stringify(refs) + ';\n');

console.log('Letter words:');
QAIDA_LETTERS.forEach(function (l) { console.log('  ' + l.char + '  ' + letterWords[l.id] + '  ' + refs[letterWords[l.id]].join(':')); });
console.log('Words with a recording: ' + Object.keys(refs).length);
