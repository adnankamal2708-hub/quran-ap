/**
 * build-quran-map.js — the data behind the Quran map
 *
 * Writes js/quran/quran-map-data.js (docs/superpowers/specs/
 * 2026-11-17-quran-map-design.md):
 *   pages  Madinah Mushaf page starts [surah, ayah], 604 + end marker
 *   juz    juz starts, 30 + end marker (both from scripts/data/tanzil-pages.json)
 *   keys   occurrence-index keys of the lesson words found in the Quran
 *   ayahs  per surah, per ayah (ayahs[s-1][a-1]): each word's index into
 *          keys, base 36, comma-separated; empty for a word that is no lesson word
 * Words are split and keyed exactly as scripts/build-occurrence-index.js
 * counts them, so a page's shading always agrees with "% of the Quran".
 *
 * Run: node scripts/build-quran-map.js
 */
'use strict';

var fs = require('fs');
var path = require('path');
var occ = require('./build-occurrence-index.js');

var ROOT = path.join(__dirname, '..');
var OUT_PATH = path.join(ROOT, 'js', 'quran', 'quran-map-data.js');
var PAGES = require('./data/tanzil-pages.json');

function loadInputs() {
  var quranText = occ.loadQuranCorpus();
  return { quranText: quranText, words: occ.loadVocabulary() };
}

function buildQuranMap(inputs) {
  var tokenKey = occ.buildFormKeys(inputs.quranText, inputs.words).tokenKey;
  var keys = [], keyIndex = {}, ayahs = [];
  for (var s = 1; s <= 114; s++) {
    ayahs.push(inputs.quranText[s].verses.map(function (verse) {
      return verse.text.split(/\s+/).filter(Boolean).map(function (token) {
        var key = tokenKey(token.trim());
        if (!key) return '';
        if (!(key in keyIndex)) { keyIndex[key] = keys.length; keys.push(key); }
        return keyIndex[key].toString(36);
      }).join(',');
    }));
  }
  return { pages: PAGES.pages, juz: PAGES.juz, keys: keys, ayahs: ayahs };
}

/** One ayah's entry as key indexes, -1 for a word that is no lesson word. */
function decodeAyah(entry) {
  return String(entry).split(',').map(function (x) { return x === '' ? -1 : parseInt(x, 36); });
}

function generateFile(map) {
  var count = map.ayahs.reduce(function (n, surah) { return n + surah.length; }, 0);
  return '// Generated by scripts/build-quran-map.js — do not edit by hand.\n' +
    '// The Quran map: page and juz starts from Tanzil Quran Metadata 1.0\n' +
    '// (tanzil.net, CC BY 3.0) and each word\'s occurrence-index key. ' + count + ' ayahs.\n' +
    'window.__QURAN_MAP = {\n' +
    'pages:' + JSON.stringify(map.pages) + ',\n' +
    'juz:' + JSON.stringify(map.juz) + ',\n' +
    'keys:' + JSON.stringify(map.keys) + ',\n' +
    'ayahs:[\n' +
    map.ayahs.map(function (surah) { return JSON.stringify(surah); }).join(',\n') +
    '\n]};\n';
}

function main() {
  var out = generateFile(buildQuranMap(loadInputs()));
  fs.writeFileSync(OUT_PATH, out, 'utf8');
  console.log('Wrote js/quran/quran-map-data.js: ' + (Buffer.byteLength(out) / 1024).toFixed(1) + ' KB');
}

if (require.main === module) main();

module.exports = {
  loadInputs: loadInputs,
  buildQuranMap: buildQuranMap,
  decodeAyah: decodeAyah,
  generateFile: generateFile,
};
