#!/usr/bin/env node
/**
 * scripts/build-verse-word-counts.js
 *
 * Builds js/tajweed/verse-word-counts.js from the Quran text
 * (js/quran/quran-data.js): the word count of every verse, as one array
 * per surah (index ayah-1). The Tajweed progress figure is the words of
 * the verses a learner has practised smoothly out of the Quran's total.
 * Words are counted as build-qaida-readability.js counts them
 * (whitespace-separated tokens), so the total is the same 77,428.
 *
 * Usage: node scripts/build-verse-word-counts.js
 * Rerun after changing js/quran/quran-data.js.
 */

var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');

global.window = {};
new Function(fs.readFileSync(path.join(ROOT, 'js/quran/quran-data.js'), 'utf8'))();
var QURAN = global.window.__QURAN_TEXT;

var total = 0;
var counts = {};
for (var sid = 1; sid <= 114; sid++) {
  counts[sid] = QURAN[sid].verses.map(function (v) {
    var n = v.text.split(/\s+/).filter(function (token) { return token.trim(); }).length;
    total += n;
    return n;
  });
}

var lines = Object.keys(counts).map(function (sid) {
  return '  ' + sid + ': ' + JSON.stringify(counts[sid]);
});

fs.writeFileSync(path.join(ROOT, 'js/tajweed/verse-word-counts.js'),
  '// Generated by scripts/build-verse-word-counts.js — do not edit by hand.\n\n' +
  '// Total word occurrences in the Quran text\n' +
  'var QURAN_WORD_TOTAL = ' + total + ';\n\n' +
  '// Words in each verse, by surah (index ayah - 1)\n' +
  'var VERSE_WORD_COUNTS = {\n' + lines.join(',\n') + '\n};\n\n' +
  '// Words in one verse, 0 when the verse is unknown\n' +
  'function verseWordCount(surah, ayah) {\n' +
  '  var verses = VERSE_WORD_COUNTS[surah];\n' +
  '  return (verses && verses[ayah - 1]) || 0;\n' +
  '}\n');

console.log('Words: ' + total + ', verses: ' + Object.keys(counts).reduce(function (n, s) { return n + counts[s].length; }, 0));
