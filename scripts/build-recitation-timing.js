/**
 * build-recitation-timing.js — when Al-Husary says each word
 *
 * Writes js/quran/recitation-timing.js (docs/superpowers/specs/
 * 2026-11-18-follow-along-design.md) from quran-align's word timings for
 * everyayah's Husary_64kbps recitation (github.com/cpfair/quran-align,
 * release 2016-11-24, CC BY 4.0). The download itself is not kept in the repo.
 *
 * Per ayah (ayahs[s-1][a-1]), comma-separated, base 36, in 10 ms units:
 * each word's start as a delta from the previous timed word's start (from 0
 * for the first), empty for a word with no trustworthy timing; then ';' and
 * the ayah's end as a delta from the last timed start. A word followed by a
 * pause of more than PAUSE_MS carries '.' and its own length, so nothing is
 * lit while the reciter is silent. An ayah whose words
 * don't line up with the app's text is "" (it plays without a highlight).
 *
 * Run: node scripts/build-recitation-timing.js <path/to/Husary_64kbps.json>
 */
'use strict';

var fs = require('fs');
var path = require('path');
var occ = require('./build-occurrence-index.js');

var OUT_PATH = path.join(__dirname, '..', 'js', 'quran', 'recitation-timing.js');
var UNIT_MS = 10;
var PAUSE_MS = 300;

/** The app's words per ayah, split exactly as the reader numbers them. */
function appWordCounts(quranText) {
  var counts = {};
  for (var s = 1; s <= 114; s++) {
    counts[s] = quranText[s].verses.map(function (v) { return v.text.split(/\s+/).filter(Boolean).length; });
  }
  return counts;
}

/**
 * One ayah's entry, or '' when its words don't match the app's text.
 * A segment whose end is not after its start is a failed alignment: that
 * word gets no time, so the word before it stays lit (never a wrong word).
 */
function encodeAyah(segments, wordCount) {
  var last = segments.reduce(function (n, g) { return Math.max(n, g[1]); }, 0);
  if (last !== wordCount) return '';
  var starts = [], stops = [], end = 0;
  for (var i = 0; i < wordCount; i++) { starts.push(null); stops.push(null); }
  segments.forEach(function (g) {
    if (g[2] % UNIT_MS) throw new Error('start not a multiple of ' + UNIT_MS + ' ms: ' + g);
    if (g[3] <= g[2]) return;
    starts[g[0]] = g[2];
    stops[g[0]] = Math.ceil(g[3] / UNIT_MS) * UNIT_MS;   // a few ends aren't whole units
    end = Math.max(end, stops[g[0]]);
  });
  var prev = 0, fields = [];
  for (var w = 0; w < wordCount; w++) {
    if (starts[w] === null) { fields.push(''); continue; }
    if (starts[w] < prev) return '';   // out of order: no highlight rather than a wrong one
    var field = ((starts[w] - prev) / UNIT_MS).toString(36);
    var next = nextStart(starts, w);
    if (next !== null && next - stops[w] > PAUSE_MS) field += '.' + ((stops[w] - starts[w]) / UNIT_MS).toString(36);
    fields.push(field);
    prev = starts[w];
  }
  if (end <= prev) return '';   // also catches an ayah with no usable word
  return fields.join(',') + ';' + ((end - prev) / UNIT_MS).toString(36);
}

/** The next timed word's start after word w, or null. */
function nextStart(starts, w) {
  for (var i = w + 1; i < starts.length; i++) if (starts[i] !== null) return starts[i];
  return null;
}

function buildTiming(source, quranText) {
  var counts = appWordCounts(quranText);
  var ayahs = [], dropped = [];
  for (var s = 1; s <= 114; s++) ayahs.push(counts[s].map(function () { return ''; }));
  source.forEach(function (e) {
    var entry = encodeAyah(e.segments, counts[e.surah][e.ayah - 1]);
    ayahs[e.surah - 1][e.ayah - 1] = entry;
  });
  ayahs.forEach(function (surah, si) {
    surah.forEach(function (entry, ai) { if (!entry) dropped.push((si + 1) + ':' + (ai + 1)); });
  });
  return { ayahs: ayahs, dropped: dropped };
}

function generateFile(timing) {
  return '// Generated by scripts/build-recitation-timing.js — do not edit by hand.\n' +
    '// Word timings for everyayah.com Husary_64kbps from quran-align by Collin Fair\n' +
    '// (github.com/cpfair/quran-align, release 2016-11-24), CC BY 4.0.\n' +
    'window.__RECITATION_TIMING = {\nunit:' + UNIT_MS + ',\nayahs:[\n' +
    timing.ayahs.map(function (surah) { return JSON.stringify(surah); }).join(',\n') +
    '\n]};\n';
}

module.exports = { encodeAyah: encodeAyah, buildTiming: buildTiming, UNIT_MS: UNIT_MS };

if (require.main === module) {
  var src = process.argv[2];
  if (!src) { console.error('Usage: node scripts/build-recitation-timing.js <Husary_64kbps.json>'); process.exit(1); }
  var timing = buildTiming(JSON.parse(fs.readFileSync(src, 'utf8')), occ.loadQuranCorpus());
  var out = generateFile(timing);
  fs.writeFileSync(OUT_PATH, out);
  var total = timing.ayahs.reduce(function (n, s) { return n + s.length; }, 0);
  console.log('timed ' + (total - timing.dropped.length) + ', dropped ' + timing.dropped.length +
    ' (' + timing.dropped.join(' ') + '), ' + out.length + ' bytes');
}
